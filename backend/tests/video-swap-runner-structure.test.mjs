import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('P8 runner, seam, merge routes and recovery are wired', () => {
  const route = read('src/routes/videoProjects.ts')
  const runner = read('src/services/video-swap-runner.ts')
  const seam = read('src/services/video-swap-seam.ts')
  const media = read('src/services/video-swap-media.ts')
  const index = read('src/index.ts')
  const schema = read('src/db/schema.ts')
  const sqlite = read('src/db/sqlite-schema.ts')
  const verify = read('scripts/verify-schema.ts')

  assert.match(route, /'\/:id\/generate'/)
  assert.match(route, /'\/:id\/runs'/)
  assert.match(route, /'\/:id\/runs\/:runId'/)
  assert.match(route, /'\/:id\/runs\/:runId\/logs'/)
  assert.match(route, /'\/:id\/runs\/:runId\/cancel'/)
  assert.match(route, /'\/:id\/chunks\/:chunkId\/retry'/)
  assert.match(route, /'\/route-preview'/)
  assert.match(runner, /do not add or remove people/)
  assert.match(runner, /uploadGatewayVideo|uploadVideo/)
  assert.match(runner, /mapGatewayJob/)
  assert.match(runner, /coreFramesOf/)
  assert.match(runner, /recoverInterruptedVideoSwapRuns/)
  assert.match(runner, /onlyChunkIds/)
  assert.match(seam, /computeSeamMetrics/)
  assert.match(seam, /faceSimilarity/)
  assert.match(runner, /inputs\.duration_seconds = Math\.max\(0\.2, \(chunk\.sourceEndMs - chunk\.sourceStartMs\) \/ 1000\)/)
  assert.doesNotMatch(runner, /continuity_reference/)
  assert.doesNotMatch(runner, /Keep exactly the same identity/)
  assert.match(runner, /reference_face_\$\{i \+ 1\}/)
  assert.doesNotMatch(runner, /inputs\.reference_face_1 = continuityDataUrl/)
  assert.match(runner, /ensurePromptPlanForGeneration/)
  assert.match(runner, /buildDefaultFacePromptPlan/)
  assert.match(runner, /selectWorkflowSlug/)
  assert.match(runner, /workflowSlugFor\(run\.mode, settings, chunkSeconds\)/)
  assert.match(runner, /characterRelayWarmupFrames/)
  assert.match(runner, /extractSourceChunkWithWarmup/)
  assert.match(runner, /resolveFaceEngine/)
  assert.match(runner, /runFaceFusion/)
  assert.match(runner, /useFaceFusion/)
  assert.match(runner, /gateway\.submitJob\(config, workflowSlug, inputs\)/)
  assert.match(media, /muxOriginalAudio/)
  assert.match(media, /concatVideoParts/)
  assert.match(media, /trimChunkVideo/)
  assert.match(index, /recoverInterruptedVideoSwapRuns\(\)/)
  assert.match(schema, /paramsJson/)
  assert.match(schema, /edlJson/)
  assert.match(schema, /seamJson/)
  assert.match(sqlite, /ADD COLUMN params_json|params_json TEXT/)
  assert.match(sqlite, /ADD COLUMN seam_json|seam_json TEXT/)
  assert.match(verify, /params_json/)
  assert.match(verify, /seam_json/)
})
